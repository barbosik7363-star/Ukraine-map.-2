struct RegionShape: Shape {
    let geometry: RegionGeometry

    func path(in rect: CGRect) -> Path {
        var path = Path()
        for ring in geometry.rings where ring.count > 2 {
            let pts = ring.map { UkraineGeometry.project($0, in: rect) }
            path.move(to: pts[0])
            for p in pts.dropFirst() { path.addLine(to: p) }
            path.closeSubpath()
        }
        return path
    }
}

extension AlertLevel {
    var mapFill: Color {
        switch self {
        case .clear: return Color(white: 0.24)
        case .yellow: return Color(red: 0.78, green: 0.65, blue: 0.24)
        case .red: return Color(red: 0.66, green: 0.27, blue: 0.23)
        case .darkRed: return Color(red: 0.45, green: 0.17, blue: 0.15)
        }
    }
}
